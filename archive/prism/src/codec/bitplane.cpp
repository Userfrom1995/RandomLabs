// X6c hyperprior: apply a per-subband probability-calibration factor `s` to a
// predicted P(0)*M probability. p0 in [1, 65534] keeps rANS valid (P(0),P(1) both
// strictly inside (0, M)). Sub-1 factors sharpen the predicted peak (assume the
// model over-spreads the mass); super-1 factors flatten it. Symmetric encode/decode.
static inline uint16_t scale_p0(uint16_t p, float s) {
    if (s == 1.0f) return p;
    float v = (float)p * s;
    if (v < 1.0f) v = 1.0f;
    if (v > 65534.0f) v = 65534.0f;
    return (uint16_t)std::lround(v);
}

int floor_log2(uint32_t v) {
    if (v == 0) return -1;
    return 31 - __builtin_clz(v);
}

int mag_bucket(int32_t v) {
    if (v <= 0) return 0;
    return (int)std::min(7, floor_log2((uint32_t)v));
}

// R6-B class: (symtype x bitplane-bucket). Both terms are known at BOTH encode
// and decode time BEFORE the bit is decided (symtype is the walk state; p is the
// current bitplane index), so the class is perfectly symmetric and the
// transmitted per-class histogram stays a valid static prior. 3 symtypes x 4
// bitplane buckets = 12 classes (research-route6 section 3).
inline int r6b_class(uint8_t symtype, int p) {
    int pb = (p < 3) ? 0 : (p < 6) ? 1 : (p < 9) ? 2 : 3;
    return (int)symtype * 4 + pb;
}

// R6-B blend model: a transmitted per-(subband, class) static P(0) backbone
// combined with the learned context model (MLP prior + per-context adaptive
// EMA, i.e. LearnedModel). The static histogram is the JXL-Modular "transmitted
// tree" that removes the per-subband systematic bias and seeds every context at
// its class empirical distribution instead of p=0.5; the learned model keeps the
// magnitude-aware prior and refines rich contexts. Both evolve identically at
// encode and decode (the learned weights are baked constants, the static table
// is transmitted), so the rANS stream round-trips byte-exact. R6B_W_STATIC is a
// global blend weight (0 = pure learned, 1 = pure transmitted histogram).
struct StaticAdaptiveModel {
    static constexpr uint32_t M = 1u << 16;
    static constexpr float W_STATIC = 0.35f; // transmitted-histogram weight
    std::vector<std::vector<uint16_t>> sp0;  // [NS][R6B_CLASSES]
    LearnedModel learned;

    void init(size_t NS, const std::vector<std::vector<uint16_t>>& s) {
        sp0 = s;
        learned = LearnedModel();
    }
    uint16_t predict(const LCFeat& f, uint8_t oi, uint8_t cls) const {
        uint16_t lp = learned.predict(f);
        uint16_t sp = sp0[oi][cls];
        float w = W_STATIC;
        int b = (int)(w * (float)sp + (1.0f - w) * (float)lp);
        if (b < 1) b = 1;
        if (b > (int)M - 1) b = (int)M - 1;
        return (uint16_t)b;
    }
    void update(const LCFeat& f, uint8_t bit) { learned.update(f, bit); }
};

// R6-C cluster model: a transmitted per-cluster static P(0) backbone combined
// with the learned context model (MLP prior + per-context adaptive EMA). The
// cluster id is a pure function of the MLP prior (see r6c_cluster), so it is
// identical at encode and decode and the static table stays a valid prior. The
// static histogram removes cold-start for rare fine contexts (which the EMA
// never sees enough symbols to converge) by seeding every cluster at its
// empirical distribution; the learned model keeps the magnitude-aware prior and
// refines rich clusters. Both evolve identically at encode and decode (the
// learned weights are baked constants; the static table is transmitted), so the
// rANS stream round-trips byte-exact.
struct StaticClusterModel {
    static constexpr uint32_t M = 1u << 16;
    static constexpr float W_STATIC = 0.75f; // transmitted-histogram weight
    int NB = 0;
    std::vector<uint16_t> sp0;   // [NB] transmitted P(0)*M
    LearnedModel learned;

    void init(int nb, const std::vector<std::vector<uint32_t>>& cnt) {
        NB = nb;
        learned = LearnedModel();
        sp0.assign(nb, (uint16_t)(M / 2));
        for (int i = 0; i < nb; ++i) {
            uint32_t c0 = cnt[i][0], c1 = cnt[i][1];
            uint32_t tot = c0 + c1;
            sp0[i] = (tot == 0) ? (uint16_t)(M / 2)
                                : (uint16_t)((uint32_t)((uint64_t)c0 * M / tot) & 0xFFFF);
        }
    }
    uint16_t predict(const LCFeat& f, int cluster, uint16_t mlp_p0) const {
        uint16_t lp = learned.predict_with(f, mlp_p0);
        uint16_t sp = (cluster >= 0 && cluster < NB) ? sp0[cluster] : (uint16_t)(M / 2);
        float w = W_STATIC;
        int b = (int)(w * (float)sp + (1.0f - w) * (float)lp);
        if (b < 1) b = 1;
        if (b > (int)M - 1) b = (int)M - 1;
        return (uint16_t)b;
    }
    void update(const LCFeat& f, uint8_t bit) { learned.update(f, bit); }
};

// R6-C cluster id: map a symbol to a learned context cluster. The learned MLP
// P(0) (symmetrically available at both encode and decode) is quantised into
// KB probability buckets; the symtype separates significance / sign /
// refinement so they keep disjoint static histograms. All three terms are
// known before the bit is decided, so the cluster is perfectly symmetric.
inline int r6c_cluster(uint8_t symtype, uint16_t p0, int kb) {
    int bucket = (int)((uint64_t)p0 * (uint32_t)kb / StaticClusterModel::M);
    if (bucket >= kb) bucket = kb - 1;
    return (int)symtype * kb + bucket;
}

// Route 6D (issue #130): read the raw magnitude for a property-tree feature id.
inline int r6d_raw_feat(const R6DRaw& r, int feat) {
    switch (feat) {
        case R6D_FEAT_W:   return r.mW;
        case R6D_FEAT_N:   return r.mN;
        case R6D_FEAT_E:   return r.mE;
        case R6D_FEAT_S:   return r.mS;
        case R6D_FEAT_NW:  return r.mNW;
        case R6D_FEAT_NE:  return r.mNE;
        case R6D_FEAT_SW:  return r.mSW;
        case R6D_FEAT_SE:  return r.mSE;
        case R6D_FEAT_PARENT: return r.mParent;
        case R6D_FEAT_LUMA:   return r.mLuma;
        case R6D_FEAT_OWN:    return r.mOwn;
        case R6D_FEAT_PPOS:   return r.ppos;
        case R6D_FEAT_SYMTYPE: return (int)r.symtype;
        case R6D_FEAT_ORIENT:  return (int)r.orient;
        case R6D_FEAT_LEVEL:   return (int)r.level;
        case R6D_FEAT_PARENT_SIG: return (int)r.parent_sig;
        default: return 0;
    }
}

// Fill the RAW (un-quantised) feature snapshot for the symbol at (x,y) on bitplane
// p, mirroring learned_features exactly but storing RAW magnitudes (not log2
// buckets). The single source of truth so encode / decode / train agree.
inline void r6d_raw_features(const std::vector<uint8_t>& sig,
                             const std::vector<int32_t>& curmag,
                             const std::vector<int32_t>* pmag, int pw, int ph,
                             const std::vector<int32_t>* lmag,
                             int w, int h, int x, int y, int p, int symtype,
                             int orient, int level, int parent_sig, int fc, int dg,
                             R6DRaw& r) {
    (void)fc; (void)dg;
    auto raw_at = [&](int nx, int ny) -> int {
        if (nx >= 0 && nx < w && ny >= 0 && ny < h && sig[(size_t)ny * w + nx])
            return (int)std::abs(curmag[(size_t)ny * w + nx]);
        return 0;
    };
    r.symtype = (uint8_t)symtype;
    r.orient = (uint8_t)orient;
    r.level = (uint8_t)level;
    r.parent_sig = (uint8_t)(parent_sig ? 1 : 0);
    r.mW = raw_at(x - 1, y);
    r.mN = raw_at(x, y - 1);
    r.mE = raw_at(x + 1, y);
    r.mS = raw_at(x, y + 1);
    r.mNW = raw_at(x - 1, y - 1);
    r.mNE = raw_at(x + 1, y - 1);
    r.mSW = raw_at(x - 1, y + 1);
    r.mSE = raw_at(x + 1, y + 1);
    int pm = 0;
    if (pmag) {
        int pcx = x >> 1, pcy = y >> 1;
        if (pcx < pw && pcy < ph) pm = (int)std::abs((*pmag)[(size_t)pcy * pw + pcx]);
    }
    r.mParent = pm;
    int lm = 0;
    if (lmag) lm = (int)std::abs((*lmag)[(size_t)y * w + x]);
    r.mLuma = lm;
    r.mOwn = (int)std::abs(curmag[(size_t)y * w + x]);
    r.ppos = p;
}

// Walk the baked property tree to a leaf id in [0, R6D_K).
inline int r6d_leaf(const R6DRaw& r) {
    int node = 0;
    while (R6D_TREE[node].split != 0) {
        const R6DNode& nd = R6D_TREE[node];
        bool go_rhs;
        if (nd.split == 1) go_rhs = (r6d_raw_feat(r, nd.feat) >= (int)nd.thr);
        else go_rhs = ((int)r.symtype == (int)nd.thr); // categorical symtype
        node = go_rhs ? nd.rhs : nd.lhs;
    }
    return R6D_TREE[node].leaf;
}

// Like r6d_leaf, but defensive: clamps the leaf id into [0, K-1] so the coder is
// robust to any K (the baked tree's max leaf id is R6D_K-1). Encode and decode
// both clamp identically, so round-trip is unaffected.
inline int r6d_leaf_id(const R6DRaw& r, int K) {
    int l = r6d_leaf(r);
    if (l >= K) l = K - 1;
    return l;
}

// R6-D blend model: a transmitted per-leaf (K*3) static P(0) backbone combined
// with the retained adaptive EMA. The leaf is a function of already-coded RAW
// magnitudes only (route6d_tree.inc, baked constant), so encode/decode agree and
// the static table stays a valid prior. At W>=1.0 pure-transmitted is the
// guaranteed no-worse lower bound (each leaf pools >= its own cell's samples).
struct StaticTreeModel {
    static constexpr uint32_t M = 1u << 16;
    float W_STATIC = 0.7f; // transmitted-histogram weight
    int K = 0;
    std::vector<uint16_t> sp0;   // [K*3] transmitted P(0)*M (sign entries neutral)
    LearnedModel learned;
    void init(int k, const std::vector<uint16_t>& s) {
        K = k; sp0 = s; learned = LearnedModel();
    }
    uint16_t predict(const R6DRaw& r, const LCFeat& f) const {
        uint16_t sp = sp0[(size_t)r6d_leaf_id(r, K) * 3 + r.symtype];
        if (W_STATIC >= 1.0f) return sp;
        uint16_t lp = learned.predict(f);
        int b = (int)(W_STATIC * (float)sp + (1.0f - W_STATIC) * (float)lp);
        if (b < 1) b = 1;
        if (b > (int)M - 1) b = (int)M - 1;
        return (uint16_t)b;
    }
    void update(const LCFeat& f, uint8_t bit) { learned.update(f, bit); }
};

// Build the coding order: LL(level 0) first, then level 1..maxlevel HL,LH,HH.
std::vector<int> coding_order(const std::vector<Subband>& subs, int& maxlevel) {
    int ml = 0;
    for (const auto& s : subs) if (s.level > ml) ml = s.level;
    maxlevel = ml;
    std::vector<int> map(4 * (ml + 1), -1);
    for (int i = 0; i < (int)subs.size(); ++i)
        map[(int)subs[i].orient * (ml + 1) + subs[i].level] = i;
    std::vector<int> order;
    order.reserve(subs.size());
    if (map[0 * (ml + 1) + 0] >= 0) order.push_back(map[0 * (ml + 1) + 0]);
    for (int L = 1; L <= ml; ++L)
        for (int o = 1; o <= 3; ++o) {
            int idx = map[o * (ml + 1) + L];
            if (idx >= 0) order.push_back(idx);
        }
    return order;
}

std::vector<int> build_parent_map(const std::vector<Subband>& subs, int ml) {
    std::vector<int> map(4 * (ml + 1), -1);
    for (int i = 0; i < (int)subs.size(); ++i)
        map[(int)subs[i].orient * (ml + 1) + subs[i].level] = i;
    std::vector<int> parent(subs.size(), -1);
    for (int i = 0; i < (int)subs.size(); ++i) {
        const Subband& s = subs[i];
        if (s.level == 0) parent[i] = -1;
        else if (s.level == 1) parent[i] = map[0 * (ml + 1) + 0];
        else parent[i] = map[(int)s.orient * (ml + 1) + (s.level - 1)];
    }
    return parent;
}

// 8-neighbour significance pattern -> (fc, dg) counts (EBCOT significance
// propagation context, the legacy I28 base).
void neighbor_counts(const std::vector<uint8_t>& sig, int w, int h, int x, int y,
                     int& fc, int& dg) {
    fc = 0; dg = 0;
    auto at = [&](int nx, int ny) -> bool {
        return nx >= 0 && nx < w && ny >= 0 && ny < h && sig[(size_t)ny * w + nx];
    };
    if (at(x - 1, y)) ++fc;
    if (at(x + 1, y)) ++fc;
    if (at(x, y - 1)) ++fc;
    if (at(x, y + 1)) ++fc;
    if (at(x - 1, y - 1)) ++dg;
    if (at(x + 1, y - 1)) ++dg;
    if (at(x - 1, y + 1)) ++dg;
    if (at(x + 1, y + 1)) ++dg;
}

// R6-A: Build a mapping from subband index to its sibling subband index.
// Siblings are LH(1)<->HL(2) at the same level. LL(0) and HH(3) have no sibling (-1).
std::vector<int> build_sibling_map(const std::vector<Subband>& subbands) {
    size_t NS = subbands.size();
    std::vector<int> sibling(NS, -1);
    for (size_t i = 0; i < NS; ++i) {
        for (size_t j = i + 1; j < NS; ++j) {
            if (subbands[i].level == subbands[j].level) {
                int oi = (int)subbands[i].orient, oj = (int)subbands[j].orient;
                if ((oi == 1 && oj == 2) || (oi == 2 && oj == 1)) {
                    sibling[i] = (int)j;
                    sibling[j] = (int)i;
                }
            }
        }
    }
    return sibling;
}

// Compute the learned features for the symbol at (x, y) on bitplane p within
// subband `si`. `sig`/`mag` are the single-subband significance and RUNNING
// reconstructed-magnitude maps (already-coded coefficients only). `pmag` (when
// non-null) is the parent subband's magnitude map. `lmag`/`lsig` (when non-null)
// are the co-located LUMA subband's magnitude/significance maps (X5a cross-
// component context); indexed by the SAME oi as the subband being coded.
// Identical between encoder and decoder because both maintain `mag`/`sig` from
// the same already-coded state.
//
// R6-A: two new features (sibling-orientation magnitude, parent bitplane lag)
// appended after the base 13.
void learned_features(const std::vector<uint8_t>& sig,
                      const std::vector<int32_t>& mag,
                      const std::vector<int32_t>* pmag, int pw, int ph,
                      const std::vector<int32_t>* lmag,
                      int w, int h, int x, int y, int p, int symtype,
                      int level, LCFeat& f,
                      const std::vector<int32_t>* sib_mag = nullptr,
                      int parent_topbit = -1,
                      int sib_w = 0, int sib_h = 0) {
    int nm = 0;
    auto nmag_at = [&](int nx, int ny) {
        if (nx >= 0 && nx < w && ny >= 0 && ny < h && sig[(size_t)ny * w + nx])
            nm = std::max(nm, (int)mag[(size_t)ny * w + nx]);
    };
    nmag_at(x - 1, y); nmag_at(x + 1, y); nmag_at(x, y - 1); nmag_at(x, y + 1);
    nmag_at(x - 1, y - 1); nmag_at(x + 1, y - 1); nmag_at(x - 1, y + 1); nmag_at(x + 1, y + 1);
    int pm = 0;
    if (pmag) {
        int pcx = x >> 1, pcy = y >> 1;
        if (pcx < pw && pcy < ph) pm = (int)(*pmag)[(size_t)pcy * pw + pcx];
    }
    int lm = 0, ls = 0;
    if (lmag) lm = (int)std::abs((*lmag)[(size_t)y * w + x]), ls = ((*lmag)[(size_t)y * w + x] != 0);
    uint8_t nmag = (uint8_t)mag_bucket(nm);
    uint8_t pmag_b = (uint8_t)mag_bucket(pm);
    uint8_t ownmag = 0;
    if (symtype == 1) ownmag = (uint8_t)std::min(7, p);                   // sign: msb == p
    else if (symtype == 2) ownmag = (uint8_t)mag_bucket(mag[(size_t)y * w + x]); // refine
    // R6-A F7: sibling-orientation magnitude (HL<->LH correlation).
    uint8_t sib_m = 0;
    if (sib_mag && sib_w > 0 && sib_h > 0) {
        if (x >= 0 && x < sib_w && y >= 0 && y < sib_h) {
            int32_t sm = (*sib_mag)[(size_t)y * sib_w + x];
            if (sm != 0) sib_m = (uint8_t)mag_bucket(sm);
        }
    }
    // R6-A F8: parent-child bitplane lag (autocorrelation).
    uint8_t pplag = 0;
    if (parent_topbit >= 0 && parent_topbit > p)
        pplag = (uint8_t)std::min(7, parent_topbit - p);

    f = make_lcfeat((uint8_t)symtype, 0, 0, 0, 0, nmag, pmag_b, ownmag, (uint8_t)std::min(7, p),
                    (uint8_t)std::min(5, level), (uint8_t)mag_bucket(lm),
                    (uint8_t)(ls ? 1 : 0), sib_m, pplag);
}

