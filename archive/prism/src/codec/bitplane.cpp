// R9: build the raw already-coded magnitude snapshot `r` for the symbol at
// (x,y) on bitplane p, used to key the fixed tree-quantized EMA. Mirrors the
// argument list of learned_features so the two stay in lock-step.
inline R6DRaw make_r6d_raw(const std::vector<uint8_t>& sig,
                           const std::vector<int32_t>& curmag,
                           const std::vector<int32_t>* pmag, int pw, int ph,
                           const std::vector<int32_t>* lmag,
                           int w, int h, int x, int y, int p, int symtype,
                           int orient, int level, int parent_sig, int fc, int dg) {
    R6DRaw r;
    r6d_raw_features(sig, curmag, pmag, pw, ph, lmag, w, h, x, y, p, symtype,
                     orient, level, parent_sig, fc, dg, r);
    return r;
}

uint32_t BitplaneCoder::context_id(Subband::Orient o, bool parent_sig, int fc, int dg) {
    uint32_t orient = (uint32_t)o;          // 0..3  (2 bits)
    uint32_t ps = parent_sig ? 1u : 0u;     // 1 bit
    uint32_t f = (fc > 4) ? 4u : (uint32_t)fc;  // 0..4 (3 bits)
    uint32_t d = (dg > 4) ? 4u : (uint32_t)dg;  // 0..4 (3 bits)
    return orient + ps * 4u + f * 8u + d * 40u; // base in [0, 199]
}

static inline uint32_t coarse_ctx(uint32_t base, int symtype) {
    return base + (uint32_t)symtype * 200u; // 0..199 sig, 200..399 sign, 400..599 refine
}

BitplaneCoder::Result BitplaneCoder::encode(const std::vector<Subband>& subbands,
                                            int maxbits_override,
                                            const std::vector<std::vector<int32_t>>* luma_mag,
                                            const std::vector<float>* sub_scale) const {
    int ml = 0;
    auto order = coding_order(subbands, ml);
    auto parent = build_parent_map(subbands, ml);
    auto sibling = build_sibling_map(subbands);
    size_t NS = subbands.size();

    // Per-subband bitplane range (EBCOT-style): each subband keeps its own B so
    // tiny AC bands are not forced to emit the global LL bit-depth as wasted
    // all-zero significance bits. Indexed by original subband index oi.
    std::vector<uint8_t> sub_maxbits(NS, 0);
    for (size_t oi = 0; oi < NS; ++oi) {
        int B = 1;
        for (int32_t c : subbands[oi].coeffs) {
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            int b = (m == 0) ? 0 : floor_log2(m) + 1;
            if (b > B) B = b;
        }
        if (maxbits_override > 0) B = maxbits_override;
        sub_maxbits[oi] = (uint8_t)B;
    }

    // Shared per-subband state, indexed by original oi. Shared so a child
    // subband's PARENT magnitude/context is available while it is coded (the
    // critical X3b fix: previously each subband was encoded in isolation, so
    // parent features were always zero at inference).
    std::vector<std::vector<uint8_t>> sig(NS);
    std::vector<std::vector<int32_t>> magv(NS), curmag(NS);
    std::vector<std::vector<uint8_t>> sgn(NS);
    std::vector<std::vector<int>> topbit(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = subbands[oi].coeffs.size();
        sig[oi].assign(n, 0);
        magv[oi].resize(n);
        curmag[oi].assign(n, 0);
        sgn[oi].resize(n);
        topbit[oi].assign(n, -1);
        for (size_t ci = 0; ci < n; ++ci) {
            int32_t c = subbands[oi].coeffs[ci];
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            magv[oi][ci] = (int32_t)m;
            sgn[oi][ci] = (c < 0) ? 1 : 0;
            topbit[oi][ci] = (m == 0) ? -1 : floor_log2(m);
        }
    }

    uint32_t total = 0;
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        int B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        total += (uint32_t)(n * (size_t)B);
        for (size_t ci = 0; ci < n; ++ci)
            if (magv[oi][ci] > 0) ++total;
    }

    std::vector<std::vector<uint8_t>> streams(NS);
    // One shared predictor across the whole plane so the EMA branch evolves the
    // same way it did during training (collect_samples walks all subbands of a
    // plane with a single persistent model). Encode and decode both share one
    // model per plane, so roundtrip stays byte-exact.
    LearnedModel model;
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = subbands[oi];
        float sc = (sub_scale && oi < sub_scale->size()) ? (*sub_scale)[oi] : 1.0f;
        int w = s.w, h = s.h, B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? subbands[pidx].w : 0;
        int ph = (pidx >= 0) ? subbands[pidx].h : 0;
        int sib_idx = sibling[oi];
        const std::vector<int32_t>* sib_mag_ptr = (sib_idx >= 0) ? &curmag[sib_idx] : nullptr;
        int sib_w = (sib_idx >= 0) ? subbands[sib_idx].w : 0;
        int sib_h = (sib_idx >= 0) ? subbands[sib_idx].h : 0;
        std::vector<uint8_t> bits;
        std::vector<uint16_t> p0;
        bits.reserve(n * (size_t)B + n);
        p0.reserve(n * (size_t)B + n);
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < n; ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                int ptb = -1;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph) {
                        parent_sig = sig[pidx][(size_t)pcy * pw + pcx] != 0;
                        ptb = (curmag[pidx][(size_t)pcy * pw + pcx] != 0)
                            ? floor_log2((uint32_t)curmag[pidx][(size_t)pcy * pw + pcx])
                            : -1;
                    }
                }
                int fc = 0, dg = 0;
                neighbor_counts(sig[oi], w, h, x, y, fc, dg);
                if (sig[oi][ci] == 0) {
                    bool becomes = (topbit[oi][ci] == p);
                    uint8_t bit = becomes ? 1 : 0;
                    LCFeat f; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 0, s.level, f, sib_mag_ptr, ptb, sib_w, sib_h);
                     f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                     R6DRaw _r = make_r6d_raw(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 0, (int)s.orient, s.level, parent_sig, fc, dg);
                     p0.push_back(scale_p0(model.predict(f, _r), sc)); bits.push_back(bit); model.update(f, _r, bit);
                     if (becomes) {
                        uint8_t sg = sgn[oi][ci];
                        LCFeat fs; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 1, s.level, fs, sib_mag_ptr, ptb, sib_w, sib_h);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc = (uint8_t)fc; fs.dg = (uint8_t)dg;
                        R6DRaw _r = make_r6d_raw(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 1, (int)s.orient, s.level, parent_sig, fc, dg);
                        p0.push_back(scale_p0(model.predict(fs, _r), sc)); bits.push_back(sg); model.update(fs, _r, sg);
                        sig[oi][ci] = 1; curmag[oi][ci] = (int32_t)(1 << p);
                     }
                } else {
                    uint8_t bit = (uint8_t)((magv[oi][ci] >> p) & 1);
                    LCFeat f; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 2, s.level, f, sib_mag_ptr, ptb, sib_w, sib_h);
                     f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                     R6DRaw _r = make_r6d_raw(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 2, (int)s.orient, s.level, parent_sig, fc, dg);
                     p0.push_back(scale_p0(model.predict(f, _r), sc)); bits.push_back(bit); model.update(f, _r, bit);
                     if (bit) curmag[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
        BitplaneRans rans;
        streams[oi] = rans.encode(bits, p0);
    }

    Result res;
    res.streams = std::move(streams);
    res.sub_maxbits = std::move(sub_maxbits);
    res.total_symbols = total;
    return res;
}


std::vector<Subband> BitplaneCoder::decode(const std::vector<std::vector<uint8_t>>& streams,
                                            const std::vector<Subband>& layout,
                                            const std::vector<uint8_t>& sub_maxbits,
                                            uint32_t total_symbols,
                                            const std::vector<std::vector<int32_t>>* luma_mag,
                                            const std::vector<float>* sub_scale) const {
    int ml = 0;
    auto order = coding_order(layout, ml);
    auto parent = build_parent_map(layout, ml);
    auto sibling = build_sibling_map(layout);
    size_t NS = layout.size();

    std::vector<Subband> out = layout;
    for (auto& s : out) s.coeffs.assign((size_t)s.w * s.h, 0);

    std::vector<std::vector<uint8_t>> sig(NS);
    std::vector<std::vector<int32_t>> value(NS);
    std::vector<std::vector<int8_t>> signv(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = out[oi].coeffs.size();
        sig[oi].assign(n, 0); value[oi].resize(n, 0); signv[oi].assign(n, 1);
    }

    uint32_t idx = 0;
    // One shared predictor per plane (matches encode and training EMA evolution).
    LearnedModel model;
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = layout[oi];
        float sc = (sub_scale && oi < sub_scale->size()) ? (*sub_scale)[oi] : 1.0f;
        int w = s.w, h = s.h;
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? layout[pidx].w : 0, ph = (pidx >= 0) ? layout[pidx].h : 0;
        int si_idx = sibling[oi];
        const std::vector<int32_t>* sib_val_ptr = (si_idx >= 0) ? &value[si_idx] : nullptr;
        int sib_w = (si_idx >= 0) ? layout[si_idx].w : 0;
        int sib_h = (si_idx >= 0) ? layout[si_idx].h : 0;
        int B = sub_maxbits[oi];
        BitplaneRans::Decoder d; d.init(streams[oi]);
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < s.coeffs.size(); ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                int ptb = -1;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph) {
                        parent_sig = sig[pidx][(size_t)pcy * pw + pcx] != 0;
                        ptb = (value[pidx][(size_t)pcy * pw + pcx] != 0) ? floor_log2((uint32_t)std::abs(value[pidx][(size_t)pcy * pw + pcx])) : -1;
                    }
                }
                int fc = 0, dg = 0;
                neighbor_counts(sig[oi], w, h, x, y, fc, dg);
                if (sig[oi][ci] == 0) {
                    LCFeat f; learned_features(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 0, s.level, f, sib_val_ptr, ptb, sib_w, sib_h);
                     f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                     R6DRaw _r = make_r6d_raw(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 0, (int)s.orient, s.level, parent_sig, fc, dg);
                     uint8_t bit = d.decode_symbol(scale_p0(model.predict(f, _r), sc)); model.update(f, _r, bit); ++idx;
                     if (bit) {
                        LCFeat fs; learned_features(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 1, s.level, fs, sib_val_ptr, ptb, sib_w, sib_h);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc = (uint8_t)fc; fs.dg = (uint8_t)dg;
                        R6DRaw _r = make_r6d_raw(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 1, (int)s.orient, s.level, parent_sig, fc, dg);
                        uint8_t sg = d.decode_symbol(scale_p0(model.predict(fs, _r), sc)); model.update(fs, _r, sg); ++idx;
                        sig[oi][ci] = 1; signv[oi][ci] = sg ? -1 : 1;
                        value[oi][ci] = (int32_t)(1 << p);
                     }
                } else {
                    LCFeat f; learned_features(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 2, s.level, f, sib_val_ptr, ptb, sib_w, sib_h);
                     f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                     R6DRaw _r = make_r6d_raw(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 2, (int)s.orient, s.level, parent_sig, fc, dg);
                     uint8_t rb = d.decode_symbol(scale_p0(model.predict(f, _r), sc)); model.update(f, _r, rb); ++idx;
                     if (rb) value[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
    }

    if (total_symbols != 0 && idx != total_symbols)
        throw std::runtime_error("BitplaneCoder::decode: symbol count mismatch");

    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = out[oi].coeffs.size();
        for (size_t ci = 0; ci < n; ++ci)
            out[oi].coeffs[ci] = (int32_t)value[oi][ci] * signv[oi][ci];
    }
    return out;
}

std::pair<std::vector<uint8_t>, std::vector<uint16_t>>
BitplaneCoder::generate_symbols(const std::vector<Subband>& subbands, int maxbits_override,
                                const std::vector<std::vector<int32_t>>* luma_mag,
                                const std::vector<float>* sub_scale) {
    int ml = 0;
    auto order = coding_order(subbands, ml);
    auto parent = build_parent_map(subbands, ml);
    auto sibling = build_sibling_map(subbands);
    size_t NS = subbands.size();

    // Per-subband bitplane range, mirroring encode()/decode() (F2): previously a
    // single global B forced tiny AC bands to emit wasted all-zero significance
    // planes that encode/decode never produce. Indexed by original subband oi.
    std::vector<uint8_t> sub_maxbits(NS, 0);
    for (size_t oi = 0; oi < NS; ++oi) {
        int B = 1;
        for (int32_t c : subbands[oi].coeffs) {
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            int b = (m == 0) ? 0 : floor_log2(m) + 1;
            if (b > B) B = b;
        }
        if (maxbits_override > 0) B = maxbits_override;
        sub_maxbits[oi] = (uint8_t)B;
    }
    // Shared per-subband state indexed by original oi (F2b).
    std::vector<std::vector<uint8_t>> sig(NS);
    std::vector<std::vector<int32_t>> magv(NS);
    std::vector<std::vector<int32_t>> curmag(NS);
    std::vector<std::vector<uint8_t>> sgn(NS);
    std::vector<std::vector<int>> topbit(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = subbands[oi].coeffs.size();
        sig[oi].assign(n, 0); magv[oi].resize(n); curmag[oi].assign(n, 0);
        sgn[oi].resize(n); topbit[oi].assign(n, -1);
        for (size_t ci = 0; ci < n; ++ci) {
            int32_t c = subbands[oi].coeffs[ci];
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            magv[oi][ci] = (int32_t)m; sgn[oi][ci] = (c < 0) ? 1 : 0;
            topbit[oi][ci] = (m == 0) ? -1 : floor_log2(m);
        }
    }
    std::vector<uint8_t> bits; std::vector<uint16_t> p0;
    LearnedModel model;
    for (size_t si = 0; si < order.size(); ++si) {
        int oi = order[si]; const Subband& s = subbands[oi];
        float sc = (sub_scale && oi < sub_scale->size()) ? (*sub_scale)[oi] : 1.0f;
        int w = s.w, h = s.h; int pidx = parent[oi];
        int pw = (pidx >= 0) ? subbands[pidx].w : 0, ph = (pidx >= 0) ? subbands[pidx].h : 0;
        int si_idx = sibling[oi];
        const std::vector<int32_t>* sib_mag_ptr = (si_idx >= 0) ? &curmag[si_idx] : nullptr;
        int sib_w = (si_idx >= 0) ? subbands[si_idx].w : 0;
        int sib_h = (si_idx >= 0) ? subbands[si_idx].h : 0;
        int B = sub_maxbits[oi];
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < s.coeffs.size(); ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                int ptb = -1;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph) {
                        parent_sig = sig[pidx][(size_t)pcy * pw + pcx] != 0;
                        ptb = (curmag[pidx][(size_t)pcy * pw + pcx] != 0)
                            ? floor_log2((uint32_t)curmag[pidx][(size_t)pcy * pw + pcx])
                            : -1;
                    }
                }
                int fc = 0, dg = 0;
                neighbor_counts(sig[oi], w, h, x, y, fc, dg);
                if (sig[oi][ci] == 0) {
                    bool becomes = (topbit[oi][ci] == p);
                    uint8_t bit = becomes ? 1 : 0;
                    LCFeat f; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 0, s.level, f, sib_mag_ptr, ptb, sib_w, sib_h);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc=(uint8_t)fc; f.dg=(uint8_t)dg;
                    p0.push_back(scale_p0(model.predict(f), sc)); bits.push_back(bit); model.update(f, bit);
                    if (becomes) {
                        uint8_t sg = sgn[oi][ci];
                        LCFeat fs; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 1, s.level, fs, sib_mag_ptr, ptb, sib_w, sib_h);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc=(uint8_t)fc; fs.dg=(uint8_t)dg;
                        p0.push_back(scale_p0(model.predict(fs), sc)); bits.push_back(sg); model.update(fs, sg);
                        sig[oi][ci] = 1; curmag[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    uint8_t bit = (uint8_t)((magv[oi][ci] >> p) & 1);
                    LCFeat f; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 2, s.level, f, sib_mag_ptr, ptb, sib_w, sib_h);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc=(uint8_t)fc; f.dg=(uint8_t)dg;
                    p0.push_back(scale_p0(model.predict(f), sc)); bits.push_back(bit); model.update(f, bit);
                    if (bit) curmag[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
    }
    return {bits, p0};
}

bool BitplaneCoder::probe_rans(const std::vector<Subband>& subbands, int maxbits_override) {
    auto [bits, p0] = generate_symbols(subbands, maxbits_override);
    BitplaneRans r;
    auto enc = r.encode(bits, p0);
    BitplaneRans::Decoder d; d.init(enc);
    std::vector<uint8_t> out(bits.size(), 0);
    for (uint32_t k = 0; k < bits.size(); ++k) out[k] = d.decode_symbol(p0[k]);
    return out == bits;
}

void BitplaneCoder::collect_samples(const std::vector<Subband>& subbands,
                                    std::vector<LSample>& out, int maxbits_override,
                                    const std::vector<std::vector<int32_t>>* luma_mag,
                                    const std::vector<float>* sub_scale) {
    int ml = 0;
    auto order = coding_order(subbands, ml);
    auto parent = build_parent_map(subbands, ml);
    auto sibling = build_sibling_map(subbands);
    size_t NS = subbands.size();
    std::vector<uint8_t> sub_maxbits(NS, 0);
    for (size_t oi = 0; oi < NS; ++oi) {
        int B = 1;
        for (int32_t c : subbands[oi].coeffs) {
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            int b = (m == 0) ? 0 : floor_log2(m) + 1;
            if (b > B) B = b;
        }
        if (maxbits_override > 0) B = maxbits_override;
        sub_maxbits[oi] = (uint8_t)B;
    }

    // Shared per-subband state indexed by ORIGINAL subband index oi, exactly like
    // encode()/decode() (F2b: previously indexed by coding-order si, which made
    // the parent lookup sig[pidx] (an oi) read the wrong subband's map).
    std::vector<std::vector<uint8_t>> sig(NS);
    std::vector<std::vector<int32_t>> magv(NS);
    std::vector<std::vector<int32_t>> curmag(NS);
    std::vector<std::vector<uint8_t>> sgn(NS);
    std::vector<std::vector<int>> topbit(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = subbands[oi].coeffs.size();
        sig[oi].assign(n, 0); magv[oi].resize(n); curmag[oi].assign(n, 0);
        sgn[oi].resize(n); topbit[oi].assign(n, -1);
        for (size_t ci = 0; ci < n; ++ci) {
            int32_t c = subbands[oi].coeffs[ci];
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            magv[oi][ci] = (int32_t)m; sgn[oi][ci] = (c < 0) ? 1 : 0;
            topbit[oi][ci] = (m == 0) ? -1 : floor_log2(m);
        }
    }
    for (size_t si = 0; si < order.size(); ++si) {
        int oi = order[si]; const Subband& s = subbands[oi];
        int w = s.w, h = s.h; int pidx = parent[oi];
        int pw = (pidx >= 0) ? subbands[pidx].w : 0, ph = (pidx >= 0) ? subbands[pidx].h : 0;
        int B = sub_maxbits[oi];
        int sib_idx = sibling[oi];
        const std::vector<int32_t>* sib_mag_ptr = (sib_idx >= 0) ? &curmag[sib_idx] : nullptr;
        int sib_w = (sib_idx >= 0) ? subbands[sib_idx].w : 0;
        int sib_h = (sib_idx >= 0) ? subbands[sib_idx].h : 0;
        for (int p = B - 1; p >= 0; --p) {
            for (int ci = 0; ci < (int)s.coeffs.size(); ++ci) {
                int x = ci % w, y = ci / w;
                bool parent_sig = false;
                int ptb = -1;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph) {
                        parent_sig = sig[pidx][(size_t)pcy * pw + pcx] != 0;
                        ptb = (curmag[pidx][(size_t)pcy * pw + pcx] != 0)
                            ? floor_log2((uint32_t)curmag[pidx][(size_t)pcy * pw + pcx])
                            : -1;
                    }
                }
                int fc = 0, dg = 0;
                neighbor_counts(sig[oi], w, h, x, y, fc, dg);
                uint32_t base = context_id(s.orient, parent_sig, fc, dg);
                if (sig[oi][ci] == 0) {
                    bool becomes = (topbit[oi][ci] == p);
                    LCFeat f; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 0, s.level, f, sib_mag_ptr, ptb, sib_w, sib_h);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc=(uint8_t)fc; f.dg=(uint8_t)dg;
                    out.push_back({f, becomes ? 1 : 0, coarse_ctx(base, 0)});
                    if (becomes) {
                        LCFeat fs; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 1, s.level, fs, sib_mag_ptr, ptb, sib_w, sib_h);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc=(uint8_t)fc; fs.dg=(uint8_t)dg;
                        out.push_back({fs, sgn[oi][ci], coarse_ctx(base, 1)});
                        sig[oi][ci] = 1; curmag[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    uint8_t bit = (uint8_t)((magv[oi][ci] >> p) & 1);
                    LCFeat f; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 2, s.level, f, sib_mag_ptr, ptb, sib_w, sib_h);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc=(uint8_t)fc; f.dg=(uint8_t)dg;
                    out.push_back({f, bit, coarse_ctx(base, 2)});
                    if (bit) curmag[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
    }
}

StaticBitplaneResult BitplaneCoder::encode_static(
    const std::vector<Subband>& subbands, int maxbits_override,
    const std::vector<std::vector<int32_t>>* luma_mag) const {
    int ml = 0;
    auto order = coding_order(subbands, ml);
    auto parent = build_parent_map(subbands, ml);
    size_t NS = subbands.size();

    std::vector<uint8_t> sub_maxbits(NS, 0);
    for (size_t oi = 0; oi < NS; ++oi) {
        int B = 1;
        for (int32_t c : subbands[oi].coeffs) {
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            int b = (m == 0) ? 0 : floor_log2(m) + 1;
            if (b > B) B = b;
        }
        if (maxbits_override > 0) B = maxbits_override;
        sub_maxbits[oi] = (uint8_t)B;
    }

    std::vector<std::vector<uint8_t>> sig(NS);
    std::vector<std::vector<int32_t>> magv(NS), curmag(NS);
    std::vector<std::vector<uint8_t>> sgn(NS);
    std::vector<std::vector<int>> topbit(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = subbands[oi].coeffs.size();
        sig[oi].assign(n, 0); magv[oi].resize(n); curmag[oi].assign(n, 0);
        sgn[oi].resize(n); topbit[oi].assign(n, -1);
        for (size_t ci = 0; ci < n; ++ci) {
            int32_t c = subbands[oi].coeffs[ci];
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            magv[oi][ci] = (int32_t)m; sgn[oi][ci] = (c < 0) ? 1 : 0;
            topbit[oi][ci] = (m == 0) ? -1 : floor_log2(m);
        }
    }

    // Histogram + symbol stores (pass 1). We accumulate per-(subband, class)
    // counts and remember each symbol's bit so pass 2 can blend the transmitted
    // static backbone with the learned model (re-walking for the LCFeat) and
    // rANS-encode.
    StaticHist hist;
    hist.cnt.assign(NS, std::vector<uint32_t>(R6B_CLASSES * 2, 0));
    std::vector<std::vector<uint8_t>> bits_by_sub(NS);
    uint32_t total = 0;
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        int B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        total += (uint32_t)(n * (size_t)B);
        for (size_t ci = 0; ci < n; ++ci)
            if (magv[oi][ci] > 0) ++total;
    }
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = subbands[oi];
        int w = s.w, h = s.h, B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? subbands[pidx].w : 0;
        int ph = (pidx >= 0) ? subbands[pidx].h : 0;
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < n; ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph)
                        parent_sig = sig[pidx][(size_t)pcy * pw + pcx] != 0;
                }
                int fc = 0, dg = 0;
                neighbor_counts(sig[oi], w, h, x, y, fc, dg);
                uint8_t bit; uint8_t symtype;
                if (sig[oi][ci] == 0) {
                    bool becomes = (topbit[oi][ci] == p);
                    bit = becomes ? 1 : 0; symtype = 0;
                    int cls = r6b_class(0, p);
                    hist.cnt[oi][cls * 2 + bit]++;
                    bits_by_sub[oi].push_back(bit);
                    if (becomes) {
                        uint8_t sg = sgn[oi][ci]; symtype = 1;
                        int cls = r6b_class(1, p);
                        hist.cnt[oi][cls * 2 + sg]++;
                        bits_by_sub[oi].push_back(sg);
                        sig[oi][ci] = 1; curmag[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    bit = (uint8_t)((magv[oi][ci] >> p) & 1); symtype = 2;
                    int cls = r6b_class(2, p);
                    hist.cnt[oi][cls * 2 + bit]++;
                    bits_by_sub[oi].push_back(bit);
                    if (bit) curmag[oi][ci] |= (int32_t)(1 << p);
                }
                (void)symtype;
            }
        }
    }

    // Wire-representability clamp (issue #130, complements the NOTE below):
    // clamp the stored histogram itself so the returned res.hist is exactly
    // what the wire carries (16-bit per count). This makes the container-side
    // clamp a no-op and guarantees any future res.hist consumer sees
    // wire-exact counts. Small images (no count above 65535) are unaffected.
    for (size_t oi = 0; oi < NS; ++oi)
        for (uint32_t& c : hist.cnt[oi])
            if (c > 0xFFFFu) c = 0xFFFFu;

    // Build the transmitted static P(0)*M per (subband, class).
    // NOTE (issue #130, 2026-09-03): the container clamps histogram counts to
    // 16 bits on the wire, so the decoder rebuilds P(0) from CLAMPED counts.
    // The encoder must derive its backbone from the same clamped counts;
    // using raw counts desyncs the rANS stream on images where any class count
    // exceeds 65535 (every real Kodak image) while staying green on small
    // synthetic unit-test images.
    std::vector<std::vector<uint16_t>> sp0(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        sp0[oi].resize(R6B_CLASSES);
        for (int cls = 0; cls < R6B_CLASSES; ++cls) {
            uint32_t c0 = hist.cnt[oi][cls * 2 + 0];
            uint32_t c1 = hist.cnt[oi][cls * 2 + 1];
            if (c0 > 0xFFFF) c0 = 0xFFFF;
            if (c1 > 0xFFFF) c1 = 0xFFFF;
            uint32_t tot = c0 + c1;
            sp0[oi][cls] = (tot == 0) ? (uint16_t)(StaticAdaptiveModel::M / 2)
                                      : (uint16_t)((uint32_t)((uint64_t)c0 * StaticAdaptiveModel::M / tot) & 0xFFFF);
        }
    }

    // Pass 2: blend the transmitted static backbone with the learned model and
    // rANS-encode. We re-walk the coefficients (deterministic) so each symbol's
    // LCFeat + class is recomputed exactly as in pass 1 / decode, and the stored
    // bits (from pass 1) drive the rANS stream. The learned model's EMA evolves
    // identically to decode, so round-trip is byte-exact. Fresh per-subband walk
    // state (lsig/lcurmag) is used so the walk starts from scratch.
    std::vector<std::vector<uint8_t>> streams(NS);
    // Fresh per-subband walk state for the re-walk (must track parent subbands).
    std::vector<std::vector<uint8_t>> lsig(NS);
    std::vector<std::vector<int32_t>> lcurmag(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = subbands[oi].coeffs.size();
        lsig[oi].assign(n, 0);
        lcurmag[oi].assign(n, 0);
    }
    StaticAdaptiveModel model; model.init(NS, sp0);
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = subbands[oi];
        int w = s.w, h = s.h, B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? subbands[pidx].w : 0;
        int ph = (pidx >= 0) ? subbands[pidx].h : 0;
        const auto& bits = bits_by_sub[oi];
        size_t k = 0;
        std::vector<uint16_t> p0vec;
        p0vec.reserve(bits.size());
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < n; ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph)
                        parent_sig = lsig[pidx][(size_t)pcy * pw + pcx] != 0;
                }
                int fc = 0, dg = 0;
                neighbor_counts(lsig[oi], w, h, x, y, fc, dg);
                const std::vector<int32_t>* parent_cur = (pidx >= 0) ? &lcurmag[pidx] : nullptr;
                const std::vector<int32_t>* lmag = (luma_mag ? &(*luma_mag)[oi] : nullptr);
                if (lsig[oi][ci] == 0) {
                    bool becomes = (topbit[oi][ci] == p);
                    uint8_t bit = bits[k++];
                    LCFeat f; learned_features(lsig[oi], lcurmag[oi], parent_cur, pw, ph, lmag, w, h, x, y, p, 0, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    int cls = r6b_class(0, p);
                    p0vec.push_back(model.predict(f, (uint8_t)oi, (uint8_t)cls));
                    model.update(f, bit);
                    if (becomes) {
                        uint8_t sg = bits[k++];
                        LCFeat fs; learned_features(lsig[oi], lcurmag[oi], parent_cur, pw, ph, lmag, w, h, x, y, p, 1, s.level, fs);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc = (uint8_t)fc; fs.dg = (uint8_t)dg;
                        int cls = r6b_class(1, p);
                        p0vec.push_back(model.predict(fs, (uint8_t)oi, (uint8_t)cls));
                        model.update(fs, sg);
                        lsig[oi][ci] = 1; lcurmag[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    uint8_t bit = bits[k++];
                    LCFeat f; learned_features(lsig[oi], lcurmag[oi], parent_cur, pw, ph, lmag, w, h, x, y, p, 2, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    int cls = r6b_class(2, p);
                    p0vec.push_back(model.predict(f, (uint8_t)oi, (uint8_t)cls));
                    model.update(f, bit);
                    if (bit) lcurmag[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
        BitplaneRans rans;
        streams[oi] = rans.encode(bits, p0vec);
    }

    StaticBitplaneResult res;
    res.streams = std::move(streams);
    res.sub_maxbits = std::move(sub_maxbits);
    res.total_symbols = total;
    res.hist = std::move(hist);
    return res;
}

std::vector<Subband> BitplaneCoder::decode_static(
    const std::vector<std::vector<uint8_t>>& streams,
    const std::vector<Subband>& layout,
    const std::vector<uint8_t>& sub_maxbits,
    uint32_t total_symbols,
    const StaticHist& hist,
    const std::vector<std::vector<int32_t>>* luma_mag) const {
    int ml = 0;
    auto order = coding_order(layout, ml);
    auto parent = build_parent_map(layout, ml);
    size_t NS = layout.size();

    std::vector<Subband> out = layout;
    for (auto& s : out) s.coeffs.assign((size_t)s.w * s.h, 0);

    std::vector<std::vector<uint8_t>> sig(NS);
    std::vector<std::vector<int32_t>> value(NS);
    std::vector<std::vector<int8_t>> signv(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = out[oi].coeffs.size();
        sig[oi].assign(n, 0); value[oi].resize(n, 0); signv[oi].assign(n, 1);
    }

    // Rebuild the transmitted static P(0)*M per (subband, class).
    std::vector<std::vector<uint16_t>> sp0(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        sp0[oi].resize(R6B_CLASSES);
        for (int cls = 0; cls < R6B_CLASSES; ++cls) {
            uint32_t c0 = hist.cnt[oi][cls * 2 + 0];
            uint32_t c1 = hist.cnt[oi][cls * 2 + 1];
            uint32_t tot = c0 + c1;
            sp0[oi][cls] = (tot == 0) ? (uint16_t)(StaticAdaptiveModel::M / 2)
                                      : (uint16_t)((uint32_t)((uint64_t)c0 * StaticAdaptiveModel::M / tot) & 0xFFFF);
        }
    }

    uint32_t idx = 0;
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = layout[oi];
        int w = s.w, h = s.h;
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? layout[pidx].w : 0, ph = (pidx >= 0) ? layout[pidx].h : 0;
        int B = sub_maxbits[oi];
        // Per-subband model reset. This is intentional: the learned feature
        // carried into model.predict/update already includes orient + level
        // (see LearnedModel::fine_ctx), so subband contexts are disjoint; the
        // shared vs per-subband reset choice is benign but kept per-subband for
        // a fully deterministic, symmetric encode/decode accumulator.
        StaticAdaptiveModel model; model.init(NS, sp0);
        BitplaneRans::Decoder d; d.init(streams[oi]);
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < s.coeffs.size(); ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph)
                        parent_sig = sig[pidx][(size_t)pcy * pw + pcx] != 0;
                }
                int fc = 0, dg = 0;
                neighbor_counts(sig[oi], w, h, x, y, fc, dg);
                if (sig[oi][ci] == 0) {
                    LCFeat f; learned_features(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 0, s.level, f);
                f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                int cls = r6b_class(0, p);
                    uint16_t dp0 = model.predict(f, (uint8_t)oi, (uint8_t)cls);
                    uint8_t bit = d.decode_symbol(dp0);
                    model.update(f, bit); ++idx;
                    if (bit) {
                        LCFeat fs; learned_features(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 1, s.level, fs);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc = (uint8_t)fc; fs.dg = (uint8_t)dg;
                        int cls = r6b_class(1, p);
                        uint16_t dp0s = model.predict(fs, (uint8_t)oi, (uint8_t)cls);
                        uint8_t sg = d.decode_symbol(dp0s);
                        model.update(fs, sg); ++idx;
                        sig[oi][ci] = 1; signv[oi][ci] = sg ? -1 : 1;
                        value[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    LCFeat f; learned_features(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, (luma_mag ? &(*luma_mag)[oi] : nullptr), w, h, x, y, p, 2, s.level, f);
                f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                int cls = r6b_class(2, p);
                    uint16_t dp0r = model.predict(f, (uint8_t)oi, (uint8_t)cls);
                    uint8_t rb = d.decode_symbol(dp0r);
                    model.update(f, rb); ++idx;
                    if (rb) value[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
    }

    if (total_symbols != 0 && idx != total_symbols)
        throw std::runtime_error("BitplaneCoder::decode_static: symbol count mismatch");

    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = out[oi].coeffs.size();
        for (size_t ci = 0; ci < n; ++ci)
            out[oi].coeffs[ci] = (int32_t)value[oi][ci] * signv[oi][ci];
    }
    return out;
}

StaticClusterBitplaneResult BitplaneCoder::encode_static_cluster(
    const std::vector<Subband>& subbands, int kb, int maxbits_override,
    const std::vector<std::vector<int32_t>>* luma_mag) const {
    int ml = 0;
    auto order = coding_order(subbands, ml);
    auto parent = build_parent_map(subbands, ml);
    size_t NS = subbands.size();
    int NB = 3 * kb;

    std::vector<uint8_t> sub_maxbits(NS, 0);
    for (size_t oi = 0; oi < NS; ++oi) {
        int B = 1;
        for (int32_t c : subbands[oi].coeffs) {
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            int b = (m == 0) ? 0 : floor_log2(m) + 1;
            if (b > B) B = b;
        }
        if (maxbits_override > 0) B = maxbits_override;
        sub_maxbits[oi] = (uint8_t)B;
    }

    std::vector<std::vector<uint8_t>> sig(NS);
    std::vector<std::vector<int32_t>> magv(NS), curmag(NS);
    std::vector<std::vector<uint8_t>> sgn(NS);
    std::vector<std::vector<int>> topbit(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = subbands[oi].coeffs.size();
        sig[oi].assign(n, 0); magv[oi].resize(n); curmag[oi].assign(n, 0);
        sgn[oi].resize(n); topbit[oi].assign(n, -1);
        for (size_t ci = 0; ci < n; ++ci) {
            int32_t c = subbands[oi].coeffs[ci];
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            magv[oi][ci] = (int32_t)m; sgn[oi][ci] = (c < 0) ? 1 : 0;
            topbit[oi][ci] = (m == 0) ? -1 : floor_log2(m);
        }
    }

    // Pass 1: walk and accumulate per-cluster counts. The cluster id is derived
    // from the learned MLP prior (a baked constant, symmetric at decode). We
    // only READ the prior here (no EMA update), so pass 2 starts the adaptive
    // model fresh and evolves it identically to decode.
    StaticClusterHist hist;
    hist.kb = kb;
    hist.cnt.assign(NB, std::vector<uint32_t>(2, 0));
    std::vector<std::vector<uint8_t>> bits_by_sub(NS);
    uint32_t total = 0;
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        int B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        total += (uint32_t)(n * (size_t)B);
        for (size_t ci = 0; ci < n; ++ci)
            if (magv[oi][ci] > 0) ++total;
    }
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = subbands[oi];
        int w = s.w, h = s.h, B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? subbands[pidx].w : 0;
        int ph = (pidx >= 0) ? subbands[pidx].h : 0;
        const std::vector<int32_t>* lmag = (luma_mag ? &(*luma_mag)[oi] : nullptr);
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < n; ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph)
                        parent_sig = sig[pidx][(size_t)pcy * pw + pcx] != 0;
                }
                int fc = 0, dg = 0;
                neighbor_counts(sig[oi], w, h, x, y, fc, dg);
                uint8_t bit;
                if (sig[oi][ci] == 0) {
                    bool becomes = (topbit[oi][ci] == p);
                    bit = becomes ? 1 : 0;
                    LCFeat f; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, lmag, w, h, x, y, p, 0, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    // MLP prior is computed once per symbol (at the significance
                    // bit, where the own magnitude is still 0) and reused for the
                    // sign and every refinement bit so the cluster id stays a
                    // per-symbol constant. Symmetric at encode/decode.
                    uint16_t mlp0 = learned_predict_p0(f);
                    int cluster = r6c_cluster(0, mlp0, kb);
                    hist.cnt[cluster][bit]++;
                    bits_by_sub[oi].push_back(bit);
                    if (becomes) {
                        uint8_t sg = sgn[oi][ci];
                        LCFeat fs; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, lmag, w, h, x, y, p, 1, s.level, fs);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc = (uint8_t)fc; fs.dg = (uint8_t)dg;
                        int csg = r6c_cluster(1, mlp0, kb);
                        hist.cnt[csg][sg]++;
                        bits_by_sub[oi].push_back(sg);
                        sig[oi][ci] = 1; curmag[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    bit = (uint8_t)((magv[oi][ci] >> p) & 1);
                    LCFeat f; learned_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr), pw, ph, lmag, w, h, x, y, p, 2, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    uint16_t mlp0 = learned_predict_p0(f);
                    int cluster = r6c_cluster(2, mlp0, kb);
                    hist.cnt[cluster][bit]++;
                    bits_by_sub[oi].push_back(bit);
                    if (bit) curmag[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
    }

    // Build the transmitted static P(0)*M per cluster.
    std::vector<std::vector<uint32_t>> cnt2 = hist.cnt;

    // Pass 2: re-walk, blend the transmitted cluster backbone with the learned
    // model, rANS-encode. Fresh per-subband walk state (lsig/lcurmag).
    std::vector<std::vector<uint8_t>> streams(NS);
    std::vector<std::vector<uint8_t>> lsig(NS);
    std::vector<std::vector<int32_t>> lcurmag(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = subbands[oi].coeffs.size();
        lsig[oi].assign(n, 0);
        lcurmag[oi].assign(n, 0);
    }
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = subbands[oi];
        int w = s.w, h = s.h, B = sub_maxbits[oi];
        // Per-subband model reset so the adaptive EMA evolves IDENTICALLY to
        // decode (which also resets per subband). The cluster id depends on the
        // EMA-containing learned prior, so any cross-subband EMA carry-in would
        // desync the cluster and break byte-exact round-trip.
        StaticClusterModel model; model.init(NB, cnt2);
        size_t n = subbands[oi].coeffs.size();
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? subbands[pidx].w : 0;
        int ph = (pidx >= 0) ? subbands[pidx].h : 0;
        const auto& bits = bits_by_sub[oi];
        size_t k = 0;
        std::vector<uint16_t> p0vec;
        p0vec.reserve(bits.size());
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < n; ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph)
                        parent_sig = lsig[pidx][(size_t)pcy * pw + pcx] != 0;
                }
                int fc = 0, dg = 0;
                neighbor_counts(lsig[oi], w, h, x, y, fc, dg);
                const std::vector<int32_t>* lmag = (luma_mag ? &(*luma_mag)[oi] : nullptr);
                if (lsig[oi][ci] == 0) {
                    bool becomes = (topbit[oi][ci] == p);
                    uint8_t bit = bits[k++];
                    LCFeat f; learned_features(lsig[oi], lcurmag[oi], (pidx>=0?&lcurmag[pidx]:nullptr), pw, ph, lmag, w, h, x, y, p, 0, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    uint16_t mlp0 = learned_predict_p0(f);
                    int cluster = r6c_cluster(0, mlp0, kb);
                    p0vec.push_back(model.predict(f, cluster, mlp0));
                    model.update(f, bit);
                    if (becomes) {
                        uint8_t sg = bits[k++];
                        LCFeat fs; learned_features(lsig[oi], lcurmag[oi], (pidx>=0?&lcurmag[pidx]:nullptr), pw, ph, lmag, w, h, x, y, p, 1, s.level, fs);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc = (uint8_t)fc; fs.dg = (uint8_t)dg;
                        int csg = r6c_cluster(1, mlp0, kb);
                        p0vec.push_back(model.predict(fs, csg, mlp0));
                        model.update(fs, sg);
                        lsig[oi][ci] = 1; lcurmag[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    uint8_t bit = bits[k++];
                    LCFeat f; learned_features(lsig[oi], lcurmag[oi], (pidx>=0?&lcurmag[pidx]:nullptr), pw, ph, lmag, w, h, x, y, p, 2, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    uint16_t mlp0 = learned_predict_p0(f);
                    int cluster = r6c_cluster(2, mlp0, kb);
                    p0vec.push_back(model.predict(f, cluster, mlp0));
                    model.update(f, bit);
                    if (bit) lcurmag[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
        BitplaneRans rans;
        streams[oi] = rans.encode(bits, p0vec);
    }

    StaticClusterBitplaneResult res;
    res.streams = std::move(streams);
    res.sub_maxbits = std::move(sub_maxbits);
    res.total_symbols = total;
    res.hist = std::move(hist);
    return res;
}

std::vector<Subband> BitplaneCoder::decode_static_cluster(
    const std::vector<std::vector<uint8_t>>& streams,
    const std::vector<Subband>& layout,
    const std::vector<uint8_t>& sub_maxbits,
    uint32_t total_symbols,
    const StaticClusterHist& hist,
    const std::vector<std::vector<int32_t>>* luma_mag) const {
    int ml = 0;
    auto order = coding_order(layout, ml);
    auto parent = build_parent_map(layout, ml);
    size_t NS = layout.size();
    int kb = hist.kb;
    int NB = 3 * kb;

    std::vector<Subband> out = layout;
    for (auto& s : out) s.coeffs.assign((size_t)s.w * s.h, 0);

    std::vector<std::vector<uint8_t>> sig(NS);
    std::vector<std::vector<int32_t>> value(NS);
    std::vector<std::vector<int8_t>> signv(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = out[oi].coeffs.size();
        sig[oi].assign(n, 0); value[oi].resize(n, 0); signv[oi].assign(n, 1);
    }

    // Rebuild the transmitted static P(0)*M per cluster.
    std::vector<std::vector<uint32_t>> cnt(NB, std::vector<uint32_t>(2, 0));
    for (int i = 0; i < NB && i < (int)hist.cnt.size(); ++i) {
        cnt[i][0] = hist.cnt[i][0]; cnt[i][1] = hist.cnt[i][1];
    }

    uint32_t idx = 0;
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = layout[oi];
        int w = s.w, h = s.h;
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? layout[pidx].w : 0, ph = (pidx >= 0) ? layout[pidx].h : 0;
        int B = sub_maxbits[oi];
        StaticClusterModel model; model.init(NB, cnt);
        BitplaneRans::Decoder d; d.init(streams[oi]);
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < s.coeffs.size(); ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph)
                        parent_sig = sig[pidx][(size_t)pcy * pw + pcx] != 0;
                }
                int fc = 0, dg = 0;
                neighbor_counts(sig[oi], w, h, x, y, fc, dg);
                const std::vector<int32_t>* lmag = (luma_mag ? &(*luma_mag)[oi] : nullptr);
                if (sig[oi][ci] == 0) {
                    LCFeat f; learned_features(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, lmag, w, h, x, y, p, 0, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    uint16_t mlp0 = learned_predict_p0(f);
                    int cluster = r6c_cluster(0, mlp0, kb);
                    uint16_t dp0 = model.predict(f, cluster, mlp0);
                    uint8_t bit = d.decode_symbol(dp0);
                    model.update(f, bit); ++idx;
                    if (bit) {
                        LCFeat fs; learned_features(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, lmag, w, h, x, y, p, 1, s.level, fs);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc = (uint8_t)fc; fs.dg = (uint8_t)dg;
                        int csg = r6c_cluster(1, mlp0, kb);
                        uint16_t dp0s = model.predict(fs, csg, mlp0);
                        uint8_t sg = d.decode_symbol(dp0s);
                        model.update(fs, sg); ++idx;
                        sig[oi][ci] = 1; signv[oi][ci] = sg ? -1 : 1;
                        value[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    LCFeat f; learned_features(sig[oi], value[oi], (pidx>=0?&value[pidx]:nullptr), pw, ph, lmag, w, h, x, y, p, 2, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    uint16_t mlp0 = learned_predict_p0(f);
                    int cluster = r6c_cluster(2, mlp0, kb);
                    uint16_t dp0r = model.predict(f, cluster, mlp0);
                    uint8_t rb = d.decode_symbol(dp0r);
                    model.update(f, rb); ++idx;
                    if (rb) value[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
    }

    if (total_symbols != 0 && idx != total_symbols)
        throw std::runtime_error("BitplaneCoder::decode_static_cluster: symbol count mismatch");

    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = out[oi].coeffs.size();
        for (size_t ci = 0; ci < n; ++ci)
            out[oi].coeffs[ci] = (int32_t)value[oi][ci] * signv[oi][ci];
    }
    return out;
}

StaticTreeBitplaneResult BitplaneCoder::encode_static_tree(
    const std::vector<Subband>& subbands, int k, float W, int maxbits_override,
    const std::vector<std::vector<int32_t>>* luma_mag) const {
    int ml = 0;
    auto order = coding_order(subbands, ml);
    auto parent = build_parent_map(subbands, ml);
    size_t NS = subbands.size();
    int K = k;
    int K3 = 3 * K;

    std::vector<uint8_t> sub_maxbits(NS, 0);
    for (size_t oi = 0; oi < NS; ++oi) {
        int B = 1;
        for (int32_t c : subbands[oi].coeffs) {
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            int b = (m == 0) ? 0 : floor_log2(m) + 1;
            if (b > B) B = b;
        }
        if (maxbits_override > 0) B = maxbits_override;
        sub_maxbits[oi] = (uint8_t)B;
    }

    std::vector<std::vector<uint8_t>> sig(NS);
    std::vector<std::vector<int32_t>> magv(NS), curmag(NS);
    std::vector<std::vector<uint8_t>> sgn(NS);
    std::vector<std::vector<int>> topbit(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = subbands[oi].coeffs.size();
        sig[oi].assign(n, 0); magv[oi].resize(n); curmag[oi].assign(n, 0);
        sgn[oi].resize(n); topbit[oi].assign(n, -1);
        for (size_t ci = 0; ci < n; ++ci) {
            int32_t c = subbands[oi].coeffs[ci];
            uint32_t m = (uint32_t)(c < 0 ? -c : c);
            magv[oi][ci] = (int32_t)m; sgn[oi][ci] = (c < 0) ? 1 : 0;
            topbit[oi][ci] = (m == 0) ? -1 : floor_log2(m);
        }
    }

    // Pass 1: walk and accumulate per-leaf per-symtype counts. The leaf id is
    // derived from RAW already-coded magnitudes (a baked constant at decode).
    StaticTreeHist hist;
    hist.k = K;
    hist.w = W;
    hist.sp0.assign((size_t)K3, (uint16_t)(StaticTreeModel::M / 2));
    std::vector<std::vector<uint32_t>> cnt(K3, std::vector<uint32_t>(2, 0));
    std::vector<std::vector<uint8_t>> bits_by_sub(NS);
    uint32_t total = 0;
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        int B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        total += (uint32_t)(n * (size_t)B);
        for (size_t ci = 0; ci < n; ++ci)
            if (magv[oi][ci] > 0) ++total;
    }
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = subbands[oi];
        int w = s.w, h = s.h, B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? subbands[pidx].w : 0;
        int ph = (pidx >= 0) ? subbands[pidx].h : 0;
        const std::vector<int32_t>* lmag = (luma_mag ? &(*luma_mag)[oi] : nullptr);
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < n; ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph)
                        parent_sig = sig[pidx][(size_t)pcy * pw + pcx] != 0;
                }
                int fc = 0, dg = 0;
                neighbor_counts(sig[oi], w, h, x, y, fc, dg);
                uint8_t bit; uint8_t symtype;
                if (sig[oi][ci] == 0) {
                    bool becomes = (topbit[oi][ci] == p);
                    bit = becomes ? 1 : 0; symtype = 0;
                    R6DRaw r; r6d_raw_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr),
                                               pw, ph, lmag, w, h, x, y, p, 0, (int)s.orient, s.level,
                                               parent_sig ? 1 : 0, fc, dg, r);
                    int leaf = r6d_leaf_id(r, K);
                    cnt[(size_t)leaf * 3 + 0][bit]++;
                    bits_by_sub[oi].push_back(bit);
                    if (becomes) {
                        uint8_t sg = sgn[oi][ci]; symtype = 1;
                        R6DRaw rs; r6d_raw_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr),
                                                   pw, ph, lmag, w, h, x, y, p, 1, (int)s.orient, s.level,
                                                   parent_sig ? 1 : 0, fc, dg, rs);
                        int leaf2 = r6d_leaf_id(rs, K);
                        cnt[(size_t)leaf2 * 3 + 1][sg]++;
                        bits_by_sub[oi].push_back(sg);
                        sig[oi][ci] = 1; curmag[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    bit = (uint8_t)((magv[oi][ci] >> p) & 1); symtype = 2;
                    R6DRaw r; r6d_raw_features(sig[oi], curmag[oi], (pidx>=0?&curmag[pidx]:nullptr),
                                              pw, ph, lmag, w, h, x, y, p, 2, (int)s.orient, s.level,
                                              parent_sig ? 1 : 0, fc, dg, r);
                    int leaf = r6d_leaf_id(r, K);
                    cnt[(size_t)leaf * 3 + 2][bit]++;
                    bits_by_sub[oi].push_back(bit);
                    if (bit) curmag[oi][ci] |= (int32_t)(1 << p);
                }
                (void)symtype;
            }
        }
    }

    // Build the transmitted static P(0)*M per leaf/symtype (sign forced neutral).
    for (int leaf = 0; leaf < K; ++leaf) {
        for (int st = 0; st < 3; ++st) {
            uint32_t c0 = cnt[(size_t)leaf * 3 + st][0];
            uint32_t c1 = cnt[(size_t)leaf * 3 + st][1];
            uint32_t tot = c0 + c1;
            uint16_t v;
            if (st == 1) v = (uint16_t)(StaticTreeModel::M / 2);
            else v = (tot == 0) ? (uint16_t)(StaticTreeModel::M / 2)
                                 : (uint16_t)((uint32_t)((uint64_t)c0 * StaticTreeModel::M / tot) & 0xFFFF);
            if (v < 1) v = 1;
            if (v > (uint16_t)StaticTreeModel::M - 1) v = (uint16_t)(StaticTreeModel::M - 1);
            hist.sp0[(size_t)leaf * 3 + st] = v;
        }
    }

    // Pass 2: re-walk (fresh per-subband state), blend transmitted backbone with
    // EMA, rANS-encode. Mirror encode_static_cluster exactly (model reset per
    // subband so the adaptive EMA evolves identically to decode).
    std::vector<std::vector<uint8_t>> streams(NS);
    std::vector<std::vector<uint8_t>> lsig(NS);
    std::vector<std::vector<int32_t>> lcurmag(NS);
    for (size_t oi = 0; oi < NS; ++oi) {
        size_t n = subbands[oi].coeffs.size();
        lsig[oi].assign(n, 0);
        lcurmag[oi].assign(n, 0);
    }
    for (size_t si = 0; si < order.size(); ++si) {
        size_t oi = order[si];
        const Subband& s = subbands[oi];
        int w = s.w, h = s.h, B = sub_maxbits[oi];
        size_t n = subbands[oi].coeffs.size();
        int pidx = parent[oi];
        int pw = (pidx >= 0) ? subbands[pidx].w : 0;
        int ph = (pidx >= 0) ? subbands[pidx].h : 0;
        const auto& bits = bits_by_sub[oi];
        size_t kk = 0;
        std::vector<uint16_t> p0vec;
        p0vec.reserve(bits.size());
        StaticTreeModel model; model.init(K, hist.sp0); model.W_STATIC = W;
        for (int p = B - 1; p >= 0; --p) {
            for (size_t ci = 0; ci < n; ++ci) {
                int x = (int)(ci % w), y = (int)(ci / w);
                bool parent_sig = false;
                if (pidx >= 0) {
                    int pcx = x >> 1, pcy = y >> 1;
                    if (pcx < pw && pcy < ph)
                        parent_sig = lsig[pidx][(size_t)pcy * pw + pcx] != 0;
                }
                int fc = 0, dg = 0;
                neighbor_counts(lsig[oi], w, h, x, y, fc, dg);
                const std::vector<int32_t>* lmag = (luma_mag ? &(*luma_mag)[oi] : nullptr);
                const std::vector<int32_t>* parent_cur = (pidx >= 0) ? &lcurmag[pidx] : nullptr;
                if (lsig[oi][ci] == 0) {
                    bool becomes = (topbit[oi][ci] == p);
                    uint8_t bit = bits[kk++];
                    R6DRaw r; r6d_raw_features(lsig[oi], lcurmag[oi], parent_cur, pw, ph, lmag, w, h, x, y, p, 0, (int)s.orient, s.level, parent_sig ? 1 : 0, fc, dg, r);
                    LCFeat f; learned_features(lsig[oi], lcurmag[oi], parent_cur, pw, ph, lmag, w, h, x, y, p, 0, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    p0vec.push_back(model.predict(r, f));
                    model.update(f, bit);
                    if (becomes) {
                        uint8_t sg = bits[kk++];
                        R6DRaw rs; r6d_raw_features(lsig[oi], lcurmag[oi], parent_cur, pw, ph, lmag, w, h, x, y, p, 1, (int)s.orient, s.level, parent_sig ? 1 : 0, fc, dg, rs);
                        LCFeat fs; learned_features(lsig[oi], lcurmag[oi], parent_cur, pw, ph, lmag, w, h, x, y, p, 1, s.level, fs);
                        fs.orient = (uint8_t)s.orient; fs.parent_sig = parent_sig ? 1 : 0; fs.fc = (uint8_t)fc; fs.dg = (uint8_t)dg;
                        p0vec.push_back(model.predict(rs, fs));
                        model.update(fs, sg);
                        lsig[oi][ci] = 1; lcurmag[oi][ci] = (int32_t)(1 << p);
                    }
                } else {
                    uint8_t bit = bits[kk++];
                    R6DRaw r; r6d_raw_features(lsig[oi], lcurmag[oi], parent_cur, pw, ph, lmag, w, h, x, y, p, 2, (int)s.orient, s.level, parent_sig ? 1 : 0, fc, dg, r);
                    LCFeat f; learned_features(lsig[oi], lcurmag[oi], parent_cur, pw, ph, lmag, w, h, x, y, p, 2, s.level, f);
                    f.orient = (uint8_t)s.orient; f.parent_sig = parent_sig ? 1 : 0; f.fc = (uint8_t)fc; f.dg = (uint8_t)dg;
                    p0vec.push_back(model.predict(r, f));
                    model.update(f, bit);
                    if (bit) lcurmag[oi][ci] |= (int32_t)(1 << p);
                }
            }
        }
        BitplaneRans rans;
        streams[oi] = rans.encode(bits, p0vec);
    }

    StaticTreeBitplaneResult res;
    res.streams = std::move(streams);
    res.sub_maxbits = std::move(sub_maxbits);
    res.total_symbols = total;
    res.hist = std::move(hist);
    return res;
}

