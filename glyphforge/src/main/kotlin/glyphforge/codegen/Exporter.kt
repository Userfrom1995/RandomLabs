    fun kotlinRle(font: Font, packageName: String? = null): String {
        val cls = safeClassName(font.name) + "Rle"
        val sb = StringBuilder()
        sb.append(header(font, "RLE-packed streams"))
        if (!packageName.isNullOrBlank()) sb.append("\npackage $packageName\n")
        sb.append("""

/**
 * $cls - ${font.cellWidth}x${font.cellHeight} pixel font, compact RLE form.
 * Each stream is byte 0 = grid width, byte 1 = grid height, then per row y:
 * one byte run count, then (start, length) byte pairs of set pixels.
 */
