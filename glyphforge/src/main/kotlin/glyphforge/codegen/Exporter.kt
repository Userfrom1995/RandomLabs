    // ------------------------------------------------------------------ Java

    fun java(font: Font, packageName: String? = null): String {
        val cls = safeClassName(font.name)
        val sb = StringBuilder()
        sb.append("// Generated by Glyphforge $VERSION. Do not edit.\n")
        sb.append("// Font: ${font.name}, ${font.cellWidth}x${font.cellHeight}, baseline ${font.baseline}, ")
        sb.append("default advance ${font.defaultAdvance}, ${font.glyphCount()} glyphs.\n")
        if (!packageName.isNullOrBlank()) sb.append("\npackage $packageName;\n")
        val rowType = if (font.cellWidth <= 8) "byte" else if (font.cellWidth <= 16) "short" else "int"
        sb.append("""

