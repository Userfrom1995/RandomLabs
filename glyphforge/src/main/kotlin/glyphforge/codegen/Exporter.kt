package glyphforge.codegen

import glyphforge.cli.VERSION
import glyphforge.core.Font
import glyphforge.core.Raster

/**
 * The glyph-to-code exporters: deterministic generators that turn a [Font]
 * into embeddable source in four flavors. The Kotlin, Java, and C outputs are
 * self-contained (no imports beyond the standard library) so retro projects
 * can drop them in; the test suite re-parses the emitted arrays and verifies
 * they rebuild the original pixels.
 */
enum class ExportFormat(val display: String, val extension: String) {
    KOTLIN("kotlin", "kt"),
    JAVA("java", "java"),
    C("c", "h"),
    TEXT("text", "txt");

    companion object {
        fun parse(s: String): ExportFormat = when (s.lowercase()) {
            "kotlin", "kt" -> KOTLIN
            "java" -> JAVA
            "c", "h", "c-header", "cheader" -> C
            "text", "txt" -> TEXT
            else -> throw IllegalArgumentException("unknown export format '$s' (use kotlin, java, c, or text)")
        }
    }
}

object Exporter {

    /** Rows as a list of byte values (or wider when the grid needs it). */
    private fun rowValues(g: glyphforge.core.Glyph): List<Int> {
        val v = g.width <= 8
        return (0 until g.height).map { y -> if (v) g.rowBits(y) and 0xFF else g.rowBits(y) }
    }

    private fun hexLit(value: Int, digits: Int): String =
        "0x" + value.toString(16).uppercase().padStart(digits, '0')

    private fun hexDigits(width: Int): Int = (width + 3) / 4

    /** Kotlin char literal, escaped for source. */
    fun ktChar(c: Char): String = when (c) {
        '\'' -> "'\\''"
        '\\' -> "'\\\\'"
        '\t' -> "'\\t'"
        else -> "'$c'"
    }

    /** Java char literal, escaped for source. */
    fun javaChar(c: Char): String = ktChar(c)

    /** C char literal for ASCII, else a hex code point integer. */
    fun cChar(c: Char): String {
        return if (c.code in 0x20..0x7E) {
            when (c) {
                '\'' -> "'\\''"
                '\\' -> "'\\\\'"
                else -> "'$c'"
            }
        } else {
            "0x${c.code.toString(16).uppercase().padStart(4, '0')}"
        }
    }

    fun export(font: Font, format: ExportFormat, rle: Boolean, packageName: String? = null): String = when (format) {
        ExportFormat.KOTLIN -> if (rle) kotlinRle(font, packageName) else kotlin(font, packageName)
        ExportFormat.JAVA -> java(font, packageName)
        ExportFormat.C -> if (rle) cRle(font) else c(font)
        ExportFormat.TEXT -> text(font)
    }

    private fun header(font: Font, extra: String = ""): String {
        val sb = StringBuilder()
        sb.append("// Generated by Glyphforge $VERSION. Do not edit.\n")
        sb.append("// Font: ${font.name}, ${font.cellWidth}x${font.cellHeight}, baseline ${font.baseline}, ")
        sb.append("default advance ${font.defaultAdvance}, ${font.glyphCount()} glyphs.")
        if (extra.isNotEmpty()) sb.append("\n// $extra")
        sb.append('\n')
        return sb.toString()
    }

    private fun safeClassName(name: String): String {
        val s = name.map { if (it.isLetterOrDigit() || it == '_') it else '_' }.joinToString("")
        val trimmed = s.trim('_')
        return if (trimmed.isEmpty()) "Font" else if (trimmed[0].isDigit()) "_$trimmed" else trimmed
    }

