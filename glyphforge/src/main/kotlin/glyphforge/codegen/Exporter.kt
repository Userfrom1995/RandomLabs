""".trimStart('\n'))
        for (c in font.chars()) {
            val bytes = Raster.packRle(font.glyph(c)!!)
            sb.append("        byteArrayOf(")
            sb.append(bytes.joinToString(", ") { (it.toInt() and 0xFF).toString() })
            sb.append("),\n")
        }
        sb.append("    )\n\n")
        sb.append("""

    fun index(c: Char): Int {
        for (i in CODEPOINTS.indices) if (CODEPOINTS[i] == c) return i
        return -1
    }

    fun advance(c: Char): Int = index(c).let { if (it < 0) DEFAULT_ADVANCE else ADVANCE[it] }

    /** Decodes and tests one pixel from a glyph's RLE stream. */
    fun pixel(c: Char, x: Int, y: Int): Boolean {
        val i = index(c)
        if (i < 0 || x !in 0 until CELL_WIDTH || y !in 0 until CELL_HEIGHT) return false
        val s = STREAMS[i]
        var k = 2
        for (row in 0 until CELL_HEIGHT) {
            if (k >= s.size) return false
            val n = s[k++].toInt() and 0xFF
            for (run in 0 until n) {
                if (k + 1 >= s.size) return false
                val start = s[k++].toInt() and 0xFF
                val len = s[k++].toInt() and 0xFF
                if (row == y && x >= start && x < start + len) return true
            }
        }
        return false
    }

    /** Number of bytes in a glyph's stream; smaller is more compact. */
    fun streamBytes(c: Char): Int = index(c).let { if (it < 0) 0 else STREAMS[it].size }
