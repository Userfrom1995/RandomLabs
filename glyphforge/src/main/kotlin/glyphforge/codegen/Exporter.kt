    // ------------------------------------------------------------------ C

    fun c(font: Font): String {
        val prefix = cPrefix(font.name)
        val up = prefix.uppercase()
        val rowType = if (font.cellWidth <= 8) "uint8_t" else if (font.cellWidth <= 16) "uint16_t" else "uint32_t"
        val sb = StringBuilder()
        sb.append("/* Generated by Glyphforge $VERSION. Do not edit. */\n")
        sb.append("/* Font: ${font.name}, ${font.cellWidth}x${font.cellHeight}, baseline ${font.baseline}, default advance ${font.defaultAdvance}, ${font.glyphCount()} glyphs. */\n")
        sb.append("#ifndef ${up}_FONT_H\n#define ${up}_FONT_H\n\n#include <stdint.h>\n\n")
        sb.append("#define ${up}_CELL_WIDTH  ${font.cellWidth}\n")
        sb.append("#define ${up}_CELL_HEIGHT ${font.cellHeight}\n")
        sb.append("#define ${up}_BASELINE    ${font.baseline}\n")
        sb.append("#define ${up}_DEFAULT_ADVANCE ${font.defaultAdvance}\n")
        sb.append("#define ${up}_GLYPH_COUNT ${font.glyphCount()}\n\n")
        for (c in font.chars()) {
            sb.append("static const $rowType ${prefix}_${cGlyphId(c)}[${font.cellHeight}] = { ")
            sb.append((0 until font.cellHeight).joinToString(", ") { y ->
                hexLit(font.glyph(c)!!.rowBits(y), hexDigits(font.cellWidth))
            })
            sb.append(" };\n")
        }
        sb.append("\nstruct ${prefix}_glyph {\n    int codepoint;\n    uint8_t advance;\n    const $rowType *rows;\n};\n\n")
        sb.append("static const struct ${prefix}_glyph ${prefix}_glyphs[${up}_GLYPH_COUNT] = {\n")
        for (c in font.chars()) {
            sb.append("    { ${cChar(c)}, ${font.advance(c)}, ${prefix}_${cGlyphId(c)} },\n")
        }
        sb.append("};\n\n")
        sb.append("static int ${prefix}_index(int c) {\n")
        sb.append("    for (int i = 0; i < ${up}_GLYPH_COUNT; i++) {\n")
        sb.append("        if (${prefix}_glyphs[i].codepoint == c) return i;\n")
        sb.append("    }\n    return -1;\n}\n\n")
        sb.append("static uint8_t ${prefix}_pixel(int c, int x, int y) {\n")
        sb.append("    if (x < 0 || x >= ${up}_CELL_WIDTH || y < 0 || y >= ${up}_CELL_HEIGHT) return 0;\n")
        sb.append("    int i = ${prefix}_index(c);\n")
        sb.append("    if (i < 0) return 0;\n")
        sb.append("    return (${prefix}_glyphs[i].rows[y] >> x) & 1u;\n}\n\n")
        sb.append("/* Fills out[0..(H*(W+1))-1] with the glyph rendered as on/off art (newline-separated rows). */\n")
        sb.append("static void ${prefix}_render(int c, char on, char off, char *out) {\n")
        sb.append("    int i = ${prefix}_index(c);\n")
        sb.append("    for (int y = 0; y < ${up}_CELL_HEIGHT; y++) {\n")
        sb.append("        for (int x = 0; x < ${up}_CELL_WIDTH; x++) {\n")
        sb.append("            out[y * (${up}_CELL_WIDTH + 1) + x] = (i >= 0 && (${prefix}_glyphs[i].rows[y] >> x) & 1u) ? on : off;\n")
        sb.append("        }\n")
        sb.append("        out[y * (${up}_CELL_WIDTH + 1) + ${up}_CELL_WIDTH] = '\\n';\n")
        sb.append("    }\n}\n\n")
        sb.append("#endif /* ${up}_FONT_H */\n")
        return sb.toString()
    }

    fun cRle(font: Font): String {
        val prefix = cPrefix(font.name)
        val up = prefix.uppercase()
        val sb = StringBuilder()
        sb.append("/* Generated by Glyphforge $VERSION. Do not edit. (compact RLE form) */\n")
        sb.append("/* Font: ${font.name}, ${font.cellWidth}x${font.cellHeight}, baseline ${font.baseline}, default advance ${font.defaultAdvance}, ${font.glyphCount()} glyphs. */\n")
        sb.append("#ifndef ${up}_RLE_H\n#define ${up}_RLE_H\n\n#include <stdint.h>\n\n")
        sb.append("#define ${up}_CELL_WIDTH  ${font.cellWidth}\n")
        sb.append("#define ${up}_CELL_HEIGHT ${font.cellHeight}\n")
        sb.append("#define ${up}_DEFAULT_ADVANCE ${font.defaultAdvance}\n")
        sb.append("#define ${up}_GLYPH_COUNT ${font.glyphCount()}\n\n")
        sb.append("/* Per-glyph packed streams: byte 0 = width, byte 1 = height, then per row:\n   run count byte, then (start, length) byte pairs. */\n")
        sb.append("static const uint8_t ${prefix}_streams[${up}_GLYPH_COUNT][] = {\n")
        for (c in font.chars()) {
            val bytes = Raster.packRle(font.glyph(c)!!)
            sb.append("    { ")
            sb.append(bytes.joinToString(", ") { (it.toInt() and 0xFF).toString() })
            sb.append(" },\n")
        }
        sb.append("};\n\n")
        sb.append("static const int ${prefix}_codepoints[${up}_GLYPH_COUNT] = {\n    ")
        sb.append(font.chars().joinToString(", ") { "${it.code}" })
        sb.append("\n};\n\n")
        sb.append("static const uint8_t ${prefix}_advance[${up}_GLYPH_COUNT] = {\n    ")
        sb.append(font.chars().joinToString(", ") { font.advance(it).toString() })
        sb.append("\n};\n\n")
        sb.append("static int ${prefix}_index(int c) {\n")
        sb.append("    for (int i = 0; i < ${up}_GLYPH_COUNT; i++) {\n")
        sb.append("        if (${prefix}_codepoints[i] == c) return i;\n")
        sb.append("    }\n    return -1;\n}\n\n")
        sb.append("static int ${prefix}_advance_for(int c) {\n")
        sb.append("    int i = ${prefix}_index(c);\n")
        sb.append("    return i < 0 ? ${up}_DEFAULT_ADVANCE : ${prefix}_advance[i];\n}\n\n")
        sb.append("static uint8_t ${prefix}_pixel(int c, int x, int y) {\n")
        sb.append("    int i = ${prefix}_index(c);\n")
        sb.append("    if (i < 0 || x < 0 || x >= ${up}_CELL_WIDTH || y < 0 || y >= ${up}_CELL_HEIGHT) return 0;\n")
        sb.append("    const uint8_t *s = ${prefix}_streams[i];\n")
        sb.append("    size_t k = 2;\n")
        sb.append("    for (int row = 0; row < ${up}_CELL_HEIGHT; row++) {\n")
        sb.append("        uint8_t n = s[k++];\n")
        sb.append("        for (uint8_t run = 0; run < n; run++) {\n")
        sb.append("            uint8_t start = s[k++], len = s[k++];\n")
        sb.append("            if (row == y && x >= start && x < start + len) return 1;\n")
        sb.append("        }\n")
        sb.append("    }\n    return 0;\n}\n\n")
        sb.append("#endif /* ${up}_RLE_H */\n")
        return sb.toString()
    }

    // ------------------------------------------------------------------ Text

    fun text(font: Font): String {
        val sb = StringBuilder()
        sb.append("${font.name} - ${font.cellWidth}x${font.cellHeight} pixel font, baseline ${font.baseline}, default advance ${font.defaultAdvance}, ${font.glyphCount()} glyphs\n")
        sb.append("Legend: # = pixel on, . = pixel off. Each glyph block is followed by its row hex and advance.\n\n")
        for (c in font.chars()) {
            val g = font.glyph(c)!!
            val label = if (c.isISOControl()) "U+${c.code.toString(16).uppercase().padStart(4, '0')}" else "'$c'"
            sb.append("$label U+${c.code.toString(16).uppercase().padStart(4, '0')} advance ${font.advance(c)}\n")
            for (line in Raster.toArt(g, '#', '.')) sb.append(line).append('\n')
            sb.append("rows ").append(Raster.rowHex(g).joinToString(" ")).append('\n')
            sb.append('\n')
        }
        return sb.toString()
    }

    // ------------------------------------------------------------------ helpers

    private fun cPrefix(name: String): String {
        val s = name.map { if (it.isLetterOrDigit() || it == '_') it else '_' }.joinToString("").trim('_')
        val base = if (s.isEmpty()) "glyphforge" else s.lowercase()
        return if (base[0].isDigit()) "f$base" else base
    }

    private fun cGlyphId(c: Char): String = when {
        c in 'a'..'z' || c in 'A'..'Z' || c in '0'..'9' -> c.toString()
        c == ' ' -> "space"
        else -> "u${c.code.toString(16)}"
    }

    private fun escaped(s: String): String = s.replace("\\", "\\\\").replace("\"", "\\\"")
