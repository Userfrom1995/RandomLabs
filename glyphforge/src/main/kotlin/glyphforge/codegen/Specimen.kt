package glyphforge.codegen

import glyphforge.cli.VERSION
import glyphforge.core.Font

/**
 * The HTML specimen generator: turns a [Font] into a single, self-contained,
 * zero-dependency HTML page that acts as the browser frontend for the headless
 * engine. The page embeds the font's glyph bitmaps, advances, and kern pairs
 * as JavaScript data and renders any text live in ASCII or solid-block art
 * (kerning-aware, at any scale), plus a gallery of every glyph. A font
 * designer can open the page directly from disk or serve it anywhere.
 *
 * The output is deterministic: identical fonts produce identical pages, which
 * keeps the page diffable and testable.
 */
object Specimen {

    /** Builds the specimen page for [font]. [title] overrides the page title. */
    fun generate(font: Font, title: String? = null): String {
        val t = escapeHtml(title ?: "${font.name} - Glyphforge specimen")
        val data = buildData(font)
        return header(t, font, escapeHtml(font.name)) + data + script + footer()
    }

