    /** The font data as a JavaScript object literal (one line per glyph). */
    private fun buildData(font: Font): String {
        val sb = StringBuilder()
        sb.append("<script>\n")
        sb.append("// Font data embedded by Glyphforge $VERSION. Do not edit.\n")
        sb.append("const FONT = {\n")
        sb.append("  name: '").append(escapeJs(font.name)).append("',\n")
        sb.append("  cellWidth: ").append(font.cellWidth).append(",\n")
        sb.append("  cellHeight: ").append(font.cellHeight).append(",\n")
        sb.append("  baseline: ").append(font.baseline).append(",\n")
        sb.append("  defaultAdvance: ").append(font.defaultAdvance).append(",\n")
        sb.append("  glyphs: [\n")
        for (c in font.chars()) {
            val g = font.glyph(c)!!
            sb.append("    { c: ").append(c.code)
                .append(", a: ").append(font.advance(c))
                .append(", r: [")
            for (y in 0 until g.height) {
                if (y > 0) sb.append(',')
                sb.append("0x").append(g.rowBits(y).toString(16).uppercase().padStart((font.cellWidth + 3) / 4, '0'))
            }
            sb.append("] },\n")
        }
        sb.append("  ],\n")
        sb.append("  kerns: [\n")
        for ((a, b, amount) in font.kernPairs()) {
            sb.append("    [ ").append(a.code).append(", ").append(b.code).append(", ").append(amount).append(" ],\n")
        }
        sb.append("  ]\n")
        sb.append("};\n")
        return sb.toString()
    }

    /** The (static) renderer and painter; string concatenation, no template literals. */
    private val script = """
function rowsOf(c) {
  for (var i = 0; i < FONT.glyphs.length; i++) if (FONT.glyphs[i].c === c) return FONT.glyphs[i].r;
  var blank = [];
  for (var y = 0; y < FONT.cellHeight; y++) blank.push(0);
  return blank;
}
function advanceOf(c) {
  for (var i = 0; i < FONT.glyphs.length; i++) if (FONT.glyphs[i].c === c) return FONT.glyphs[i].a;
  return FONT.defaultAdvance;
}
function kernOf(a, b) {
  for (var i = 0; i < FONT.kerns.length; i++) if (FONT.kerns[i][0] === a && FONT.kerns[i][1] === b) return FONT.kerns[i][2];
  return 0;
}
function lineCells(line) {
  var offsets = [];
  var col = 0;
  for (var i = 0; i < line.length; i++) {
    offsets.push(col);
    col += advanceOf(line.charCodeAt(i));
    if (i + 1 < line.length) col += kernOf(line.charCodeAt(i), line.charCodeAt(i + 1));
  }
  var width = line.length === 0 ? 0 : Math.max(1, col);
  var cells = [];
  for (var cx = 0; cx < width; cx++) {
    cells.push([]);
    for (var y = 0; y < FONT.cellHeight; y++) cells[cx].push(false);
  }
  for (var i = 0; i < line.length; i++) {
    var c = line.charCodeAt(i);
    var r = rowsOf(c);
    var a = advanceOf(c);
    for (var x = 0; x < a; x++) {
      var cx = offsets[i] + x;
      if (cx < 0 || cx >= width) continue;
      for (var y = 0; y < FONT.cellHeight; y++) cells[cx][y] = ((r[y] >> x) & 1) === 1;
    }
  }
  return { width: width, cells: cells };
}
function paintBlocks(cells, scale) {
  var grid = document.createElement('div');
  grid.className = 'block-grid';
  grid.style.gridTemplateColumns = 'repeat(' + cells.width + ', ' + scale + 'px)';
  for (var y = 0; y < FONT.cellHeight; y++) {
    for (var cx = 0; cx < cells.width; cx++) {
      var d = document.createElement('div');
      d.className = cells.cells[cx][y] ? 'px on' : 'px off';
      d.style.width = scale + 'px';
      d.style.height = scale + 'px';
      grid.appendChild(d);
    }
  }
  return grid;
}
function paintAscii(cells, scale) {
  var pre = document.createElement('pre');
  pre.className = 'ascii-out';
  pre.style.fontSize = scale + 'px';
  var lines = [];
  for (var y = 0; y < FONT.cellHeight; y++) {
    var s = '';
    for (var cx = 0; cx < cells.width; cx++) s += cells.cells[cx][y] ? '#' : '.';
    lines.push(s);
  }
  pre.textContent = lines.join('\n');
  return pre;
}
function preview() {
  var text = document.getElementById('text').value;
  var mode = document.getElementById('mode').value;
  var scale = parseInt(document.getElementById('scale').value, 10) || 1;
  var host = document.getElementById('preview');
  host.textContent = '';
  for (var i = 0; i < text.split('\n').length; i++) {
    var cells = lineCells(text.split('\n')[i]);
    var node = mode === 'ascii' ? paintAscii(cells, Math.max(scale, 8)) : paintBlocks(cells, scale);
    host.appendChild(node);
  }
}
function glyphGrid(glyph, cell) {
  var grid = document.createElement('div');
  grid.className = 'grid';
  grid.style.gridTemplateColumns = 'repeat(' + FONT.cellWidth + ', ' + cell + 'px)';
  for (var y = 0; y < FONT.cellHeight; y++) {
    for (var x = 0; x < FONT.cellWidth; x++) {
      var d = document.createElement('div');
      d.className = 'cell ' + (((glyph.r[y] >> x) & 1) === 1 ? 'on' : 'off');
      d.style.width = cell + 'px';
      d.style.height = cell + 'px';
      grid.appendChild(d);
    }
  }
  return grid;
}
function gallery() {
  var host = document.getElementById('gallery');
  for (var i = 0; i < FONT.glyphs.length; i++) {
    var g = FONT.glyphs[i];
    var card = document.createElement('div');
    card.className = 'glyph-card';
    var label = document.createElement('div');
    label.className = 'label';
    label.textContent = 'U+' + g.c.toString(16).toUpperCase().padStart(4, '0') + ' adv ' + g.a;
    var sample = document.createElement('div');
    sample.className = 'sample';
    sample.textContent = String.fromCharCode(g.c);
    card.appendChild(label);
    card.appendChild(sample);
    card.appendChild(glyphGrid(g, 6));
    host.appendChild(card);
  }
}
document.getElementById('text').addEventListener('input', preview);
document.getElementById('mode').addEventListener('change', preview);
document.getElementById('scale').addEventListener('input', preview);
preview();
gallery();
</script>
""".trimIndent()

    private fun footer(): String = "\n</body>\n</html>\n"

    private fun escapeHtml(s: String): String =
        s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;")

    private fun escapeJs(s: String): String = s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
}